"""Bake data/derived/tornado_climatology.json into a C# table for the designed storm (Runtime/Design/TornadoClimatology.cs)."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
d = json.loads((root / 'data/derived/tornado_climatology.json').read_text())
regions = ['plains', 'dixie', 'midwest']
qs = ['p10', 'p25', 'p50', 'p75', 'p90', 'p99']
def arr(xs): return '{ ' + ', '.join(f'{float(x):g}' for x in xs) + ' }'
def quant(block):
    rows = []
    for ef in range(6):
        b = block.get(f'EF{ef}') or block.get(f'EF{min(ef, 3)}')
        rows.append(arr([b.get(q) if b.get(q) is not None else b['p90'] for q in qs]))
    return 'new[] {\n                ' + ',\n                '.join(f'new double[] {r}' for r in rows) + ' }'
out = ['// Generated by tools/gen_climatology_cs.py from data/derived/tornado_climatology.json (SPC 1950-2025). Do not edit.',
       'namespace StormLab.Supercell', '{', '    public static partial class TornadoClimatology', '    {',
       '        /// <summary>quantile levels of the width and length tables</summary>',
       f'        public static readonly double[] Q = {arr([0.10, 0.25, 0.50, 0.75, 0.90, 0.99])};']
for name, key in [('RatingShare', None), ('WidthYd', 'width_yd'), ('LengthMi', 'length_mi')]:
    out.append(f'        /// <summary>[region][EF]{"" if key is None else "[quantile]"}: Plains, Dixie, Midwest</summary>')
    if key is None:
        rows = [arr([d['by_region'][r]['rating_share'][f'EF{e}'] for e in range(6)]) for r in regions]
        out.append(f'        public static readonly double[][] {name} = {{\n            ' + ',\n            '.join(f'new double[] {x}' for x in rows) + ' };')
    else:
        rows = [quant(d['by_region'][r][key]) for r in regions]
        out.append(f'        public static readonly double[][][] {name} = {{\n            ' + ',\n            '.join(rows) + ' };')
cf = d['cyclic_families_1995plus']
out.append('        /// <summary>[region]: tornadoes per cyclic family, 1 .. 10+</summary>')
out.append('        public static readonly double[][] FamilySize = {\n            ' + ',\n            '.join(f'new double[] {arr(cf[r]["family_size_hist_1_to_10plus"])}' for r in regions) + ' };')
out.append('        /// <summary>[region][quantile 10,25,50,75,90,99]: minutes from one tornado to the next in a family</summary>')
out.append('        public static readonly double[][] IntervalMin = {\n            ' + ',\n            '.join(f'new double[] {arr([cf[r]["interval_min"][q] for q in qs])}' for r in regions) + ' };')
out.append('        /// <summary>[region]: share of families whose strongest tornado is the first</summary>')
out.append(f'        public static readonly double[] StrongestFirst = {arr([cf[r]["strongest_is_first_share"] for r in regions])};')
out += ['    }', '}', '']
dst = root / 'unity/com.stormlab.supercell/Runtime/Design/TornadoClimatology.Data.cs'
dst.write_text('\n'.join(out), encoding='utf-8')
print('wrote', dst)
