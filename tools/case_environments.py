"""Compare each case's real proximity soundings with its preset's acceptance window (DESIGN.md §5).

  python -I tools/case_environments.py

Reads validation/real-storm-cases/catalog.json and validation/soundings/<case>_{hrrr,rap}[_inflow].json and _igra.json.
The inflow sounding (tools/fetch_inflow_soundings.py) is the case's primary one when it exists; else the point one. For every case
and source it lists the lab diagnostics (MetPy-based, 1 km mixed layer: not SPC's numbers) and marks each one inside
or outside the preset window. Per preset it then gives the observed range over its calibrate cases, which is what the
window should be revised to. The SPC tornado outcome sits beside it so tornadic and null cases can be compared.

Writes validation/real-storm-cases/environments.json and ENVIRONMENTS.md.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CASES = ROOT / "validation" / "real-storm-cases"
SND = ROOT / "validation" / "soundings"

# DESIGN.md §5 windows: (MLCAPE, MLLCL m, 0-1 km SRH, 0-6 km shear kt). Keep in step with the doc.
WINDOWS = {
    "plains_lp":       {"mlcape": (1800, 3200), "mllcl_m_agl": (1200, 1900), "srh1": (35, 150),  "shear6_kt": (28, 46)},
    "plains_classic":  {"mlcape": (2000, 4000), "mllcl_m_agl": (900, 1500),  "srh1": (150, 350), "shear6_kt": (40, 60)},
    "plains_hp":       {"mlcape": (2500, 4500), "mllcl_m_agl": (800, 1300),  "srh1": (200, 450), "shear6_kt": (35, 55)},
    "dixie_classic":   {"mlcape": (1000, 2000), "mllcl_m_agl": (500, 900),   "srh1": (250, 500), "shear6_kt": (50, 75)},
    "dixie_hp":        {"mlcape": (800, 1800),  "mllcl_m_agl": (400, 800),   "srh1": (300, 600), "shear6_kt": (50, 75)},
    "midwest_classic": {"mlcape": (1500, 3000), "mllcl_m_agl": (800, 1200),  "srh1": (150, 300), "shear6_kt": (45, 65)},
    "midwest_hp":      {"mlcape": (1500, 3500), "mllcl_m_agl": (700, 1100),  "srh1": (200, 400), "shear6_kt": (40, 60)},
    "minisupercell":   {"mlcape": (300, 1000),  "mllcl_m_agl": (400, 900),   "srh1": (150, 400), "shear6_kt": (40, 70)},
}
KEYS = ["mlcape", "mlcin", "mllcl_m_agl", "el_m_agl", "lapse_700_500_C_per_km", "srh1", "srh3", "shear6_kt", "sr_anvil_kt"]
SHORT = {"mlcape": "MLCAPE", "mlcin": "MLCIN", "mllcl_m_agl": "LCL m", "el_m_agl": "EL km", "lapse_700_500_C_per_km": "LR75",
         "srh1": "SRH1", "srh3": "SRH3", "shear6_kt": "S06 kt", "sr_anvil_kt": "SR anvil kt"}


def fmt(k, v, win):
    if v is None:
        return "-"
    s = f"{v / 1000:.1f}" if k == "el_m_agl" else (f"{v:.1f}" if isinstance(v, float) and abs(v) < 20 else f"{v:.0f}")
    if k in win:
        lo, hi = win[k]
        if v < lo:
            return s + " ↓"
        if v > hi:
            return s + " ↑"
    return s


def main():
    cat = json.loads((CASES / "catalog.json").read_text())["cases"]
    rows, by_preset = [], {}
    for c in cat:
        has_inflow = any((SND / f"{c['id']}_{m}_inflow.json").exists() for m in ("hrrr", "rap"))
        for src in ("hrrr_inflow", "rap_inflow", "hrrr", "rap", "igra"):
            f = SND / f"{c['id']}_{src}.json"
            if not f.exists():
                continue
            primary = src.endswith("_inflow") or (src != "igra" and not has_inflow)
            d = json.loads(f.read_text())["diagnostics"]
            win = WINDOWS[c["preset"]]
            inside = sum(1 for k in win if d.get(k) is not None and win[k][0] <= d[k] <= win[k][1])
            r = {"case": c["id"], "preset": c["preset"], "role": c["role"], "source": src, "primary": primary,
                 "tornadoes": c["spc"].get("tornadoes"), "max_rating": c["spc"].get("max_rating", "prelim"),
                 "in_window": f"{inside}/{len(win)}", **{k: d.get(k) for k in KEYS}}
            rows.append(r)
            if c["role"] == "calibrate" and primary:
                by_preset.setdefault(c["preset"], []).append(d)

    L = ["# Case environments vs preset windows", "",
         "Generated by `tools/case_environments.py`. Lab diagnostics (MetPy, 1 km mixed layer, Bunkers 2000; not SPC's",
         "numbers). ↓ / ↑ = below / above the preset's DESIGN.md §5 window. **Bold source** = the case's primary sounding:",
         "`_inflow` = the median of five model points 35 km upstream of the storm's radar position along its storm-relative",
         "0-1 km wind (`tools/fetch_inflow_soundings.py`), else the single point (`soundings/proximity_choices.json`);",
         "balloons are the nearest IGRA site and can be 100-250 km away and hours off. **Do not tune to a single number.**", ""]
    hdr = "| Case | Role | Src | SPC | In | " + " | ".join(SHORT[k] for k in KEYS) + " |"
    for p in WINDOWS:
        pr = [r for r in rows if r["preset"] == p]
        if not pr:
            continue
        w = WINDOWS[p]
        L += [f"## {p}", "", "Window: " + ", ".join(f"{SHORT[k]} {a}-{b}" for k, (a, b) in w.items()), "", hdr,
              "|" + "---|" * (5 + len(KEYS))]
        for r in sorted(pr, key=lambda r: (r["role"], r["case"], r["source"])):
            srcl = f"**{r['source']}**" if r["primary"] else r["source"]
            L.append(f"| {r['case']} | {r['role']} | {srcl} | {r['tornadoes'] if r['tornadoes'] is not None else '?'} "
                     f"{r['max_rating']} | {r['in_window']} | " + " | ".join(fmt(k, r[k], w) for k in KEYS) + " |")
        obs = by_preset.get(p, [])
        if obs:
            L += ["", f"Observed over {len(obs)} calibrate cases (primary soundings): " + ", ".join(
                f"{SHORT[k]} {min(v):.0f}-{max(v):.0f}" for k in w if (v := [o[k] for o in obs if o.get(k) is not None]))]
        L.append("")
    (CASES / "environments.json").write_text(json.dumps(rows, indent=1))
    (CASES / "ENVIRONMENTS.md").write_text("\n".join(L), encoding="utf-8")
    print(f"{len(rows)} soundings over {len({r['case'] for r in rows})} cases")


if __name__ == "__main__":
    main()
